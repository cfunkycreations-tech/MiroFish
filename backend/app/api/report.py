@report_bp.route('/chat', methods=['POST'])
def chat_with_report_agent():
    """
    Chat with the Report Agent
    
    The Report Agent can call retrieval tools on its own during the chat to answer the question
    
    Request (JSON):
        {
            "simulation_id": "sim_xxxx",        // required, the simulation ID
            "message": "please explain where public opinion is heading",    // required, the user message
            "chat_history": [                   // optional, the conversation history
                {"role": "user", "content": "..."},
                {"role": "assistant", "content": "..."}
            ]
        }
    
    Response:
        {
            "success": true,
            "data": {
                "response": "the Agent reply...",
                "tool_calls": [the tools it called],
                "sources": [the sources it used]
            }
        }
    """
    try:
        data = request.get_json() or {}
        
        simulation_id = data.get('simulation_id')
        message = data.get('message')
        chat_history = data.get('chat_history', [])
        
        if not simulation_id:
            return jsonify({
                "success": False,
                "error": "please provide simulation_id"
            }), 400
        
        if not message:
            return jsonify({
                "success": False,
                "error": "please provide message"
            }), 400
        
        # Fetch the simulation and project information
        manager = SimulationManager()
        state = manager.get_simulation(simulation_id)
        
        if not state:
            return jsonify({
                "success": False,
                "error": f"simulation not found: {simulation_id}"
            }), 404
        
        project = ProjectManager.get_project(state.project_id)
        if not project:
            return jsonify({
                "success": False,
                "error": f"project not found: {state.project_id}"
            }), 404
        
        graph_id = state.graph_id or project.graph_id
        if not graph_id:
            return jsonify({
                "success": False,
                "error": "the graph ID is missing"
            }), 400
        
        simulation_requirement = project.simulation_requirement or ""
        
        # Create the Agent and run the conversation
        agent = ReportAgent(
            graph_id=graph_id,
            simulation_id=simulation_id,
            simulation_requirement=simulation_requirement
        )
        
        result = agent.chat(message=message, chat_history=chat_history)
        
        return jsonify({
            "success": True,
            "data": result
        })
        
    except Exception as e:
        logger.error(f"The chat failed: {str(e)}")
        return jsonify({
            "success": False,
            "error": str(e),
            "traceback": traceback.format_exc()
        }), 500


